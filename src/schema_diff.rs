use crate::db::{ColumnInfo, DatabaseSchema, TableSchema};
use std::collections::{HashMap, HashSet};

#[derive(Debug, Clone, Default)]
pub struct SchemaDiffReport {
    pub source_name: String,
    pub target_name: String,
    pub summary: Vec<String>,
    pub migration_sql: String,
}

impl SchemaDiffReport {
    pub fn generate_migration_file_content(&self) -> String {
        let now = chrono::Local::now().format("%Y-%m-%d %H:%M:%S");
        format!(
            "-- ========================================================\n-- Schema Diff Migration: `{}` -> `{}`\n-- Generated at: {}\n-- ========================================================\n\n-- >>> UP MIGRATION (APPLY CHANGES)\n{}\n\n-- >>> SUMMARY OF CHANGES:\n-- {}\n",
            self.source_name,
            self.target_name,
            now,
            self.migration_sql,
            self.summary.join("\n-- ")
        )
    }
}

pub fn format_column_def(c: &ColumnInfo) -> String {
    let mut def = format!("`{}` {}", c.name, c.data_type);
    if c.is_nullable {
        def.push_str(" NULL");
    } else {
        def.push_str(" NOT NULL");
    }

    if let Some(def_val) = &c.default_value {
        let val = def_val.trim();
        if !val.is_empty() {
            if val.eq_ignore_ascii_case("NULL")
                || val.eq_ignore_ascii_case("CURRENT_TIMESTAMP")
                || val.chars().all(|ch| ch.is_ascii_digit() || ch == '.')
                || (val.starts_with('\'') && val.ends_with('\''))
            {
                def.push_str(&format!(" DEFAULT {val}"));
            } else {
                let escaped = val.replace('\\', "\\\\").replace('\'', "''");
                def.push_str(&format!(" DEFAULT '{escaped}'"));
            }
        }
    }

    if !c.extra.trim().is_empty() {
        def.push_str(&format!(" {}", c.extra.trim().to_uppercase()));
    }

    def
}

pub fn generate_create_table_ddl(table: &TableSchema) -> String {
    let mut ddl = format!("CREATE TABLE IF NOT EXISTS `{}` (\n", table.name);
    let mut defs = Vec::new();

    for col in &table.columns {
        defs.push(format!("  {}", format_column_def(col)));
    }

    let pks: Vec<_> = table
        .columns
        .iter()
        .filter(|c| c.is_primary_key)
        .map(|c| format!("`{}`", c.name))
        .collect();
    if !pks.is_empty() {
        defs.push(format!("  PRIMARY KEY ({})", pks.join(", ")));
    }

    let mut index_cols: HashMap<&str, (bool, Vec<&str>)> = HashMap::new();
    for idx in &table.indexes {
        if idx.index_name.eq_ignore_ascii_case("PRIMARY") {
            continue;
        }
        let entry = index_cols
            .entry(idx.index_name.as_str())
            .or_insert((!idx.non_unique, Vec::new()));
        entry.1.push(idx.column_name.as_str());
    }

    for (idx_name, (is_unique, cols)) in index_cols {
        let u = if is_unique { "UNIQUE " } else { "" };
        let cols_str = cols
            .iter()
            .map(|c| format!("`{c}`"))
            .collect::<Vec<_>>()
            .join(", ");
        defs.push(format!("  {}KEY `{}` ({})", u, idx_name, cols_str));
    }

    for fk in &table.foreign_keys {
        defs.push(format!(
            "  CONSTRAINT `{}` FOREIGN KEY (`{}`) REFERENCES `{}` (`{}`)",
            fk.constraint_name, fk.column_name, fk.referenced_table, fk.referenced_column
        ));
    }

    ddl.push_str(&defs.join(",\n"));
    let engine = if table.engine.is_empty() {
        "InnoDB"
    } else {
        &table.engine
    };
    ddl.push_str(&format!("\n) ENGINE={engine} DEFAULT CHARSET=utf8mb4;\n"));
    ddl
}

/// Compares `source` against `target` and computes the DDL migration script
/// required to bring `target` into alignment with `source`.
pub fn diff_schemas(source: &DatabaseSchema, target: &DatabaseSchema) -> SchemaDiffReport {
    diff_schemas_filtered(source, target, None)
}

/// Like [`diff_schemas`], but restricts comparison to `included_tables` when `Some`.
pub fn diff_schemas_filtered(
    source: &DatabaseSchema,
    target: &DatabaseSchema,
    included_tables: Option<&HashSet<String>>,
) -> SchemaDiffReport {
    let is_included = |name: &str| included_tables.is_none_or(|set| set.contains(name));
    let mut summary = Vec::new();
    let mut migration_sql = format!(
        "-- Schema Migration Sync: `{}` (Source) -> `{}` (Target)\n-- Generated by MySQL-Rusty\n\n",
        source.name, target.name
    );

    let target_tables: HashMap<&str, &TableSchema> =
        target.tables.iter().map(|t| (t.name.as_str(), t)).collect();
    let source_tables: HashMap<&str, &TableSchema> =
        source.tables.iter().map(|t| (t.name.as_str(), t)).collect();

    // 1. Missing Tables (present in source, missing in target)
    for src_tbl in &source.tables {
        if !is_included(&src_tbl.name) {
            continue;
        }
        if !target_tables.contains_key(src_tbl.name.as_str()) {
            summary.push(format!("+ Missing Table: `{}` (Will CREATE)", src_tbl.name));
            migration_sql.push_str(&format!("-- Create table `{}`\n", src_tbl.name));
            migration_sql.push_str(&generate_create_table_ddl(src_tbl));
            migration_sql.push('\n');
        }
    }

    // 2. Alter Existing Tables (present in both, but columns / keys differ)
    for src_tbl in &source.tables {
        if !is_included(&src_tbl.name) {
            continue;
        }
        if let Some(tgt_tbl) = target_tables.get(src_tbl.name.as_str()) {
            let tgt_cols: HashMap<&str, &ColumnInfo> = tgt_tbl
                .columns
                .iter()
                .map(|c| (c.name.as_str(), c))
                .collect();

            let mut table_alters = Vec::new();

            // Check missing columns
            for sc in &src_tbl.columns {
                if !tgt_cols.contains_key(sc.name.as_str()) {
                    summary.push(format!(
                        "+ `{}`: Missing column `{}` (Will ADD)",
                        src_tbl.name, sc.name
                    ));
                    table_alters.push(format!("ADD COLUMN {}", format_column_def(sc)));
                } else {
                    let tc = tgt_cols[sc.name.as_str()];
                    if sc.data_type.to_uppercase() != tc.data_type.to_uppercase()
                        || sc.is_nullable != tc.is_nullable
                    {
                        summary.push(format!(
                            "~ `{}`: Column `{}` definition differs (Will MODIFY)",
                            src_tbl.name, sc.name
                        ));
                        table_alters.push(format!("MODIFY COLUMN {}", format_column_def(sc)));
                    }
                }
            }

            // Check missing foreign keys
            let tgt_fk_names: HashSet<&str> = tgt_tbl
                .foreign_keys
                .iter()
                .map(|fk| fk.constraint_name.as_str())
                .collect();
            for sfk in &src_tbl.foreign_keys {
                if !tgt_fk_names.contains(sfk.constraint_name.as_str()) {
                    summary.push(format!(
                        "+ `{}`: Missing FK `{}` (Will ADD)",
                        src_tbl.name, sfk.constraint_name
                    ));
                    table_alters.push(format!(
                        "ADD CONSTRAINT `{}` FOREIGN KEY (`{}`) REFERENCES `{}` (`{}`)",
                        sfk.constraint_name,
                        sfk.column_name,
                        sfk.referenced_table,
                        sfk.referenced_column
                    ));
                }
            }

            // Check missing indexes
            let mut src_index_cols: HashMap<&str, (bool, Vec<&str>)> = HashMap::new();
            for idx in &src_tbl.indexes {
                if idx.index_name.eq_ignore_ascii_case("PRIMARY") {
                    continue;
                }
                let entry = src_index_cols
                    .entry(idx.index_name.as_str())
                    .or_insert((!idx.non_unique, Vec::new()));
                entry.1.push(idx.column_name.as_str());
            }

            let tgt_idx_names: HashSet<&str> = tgt_tbl
                .indexes
                .iter()
                .map(|i| i.index_name.as_str())
                .collect();

            for (idx_name, (is_unique, cols)) in src_index_cols {
                if !tgt_idx_names.contains(idx_name) {
                    summary.push(format!(
                        "+ `{}`: Missing index `{}` (Will ADD)",
                        src_tbl.name, idx_name
                    ));
                    let u = if is_unique { "UNIQUE " } else { "" };
                    let cols_str = cols
                        .iter()
                        .map(|c| format!("`{c}`"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    table_alters.push(format!("ADD {}INDEX `{}` ({})", u, idx_name, cols_str));
                }
            }

            if !table_alters.is_empty() {
                migration_sql.push_str(&format!("-- Alter table `{}`\n", src_tbl.name));
                migration_sql.push_str(&format!(
                    "ALTER TABLE `{}`\n  {};\n\n",
                    src_tbl.name,
                    table_alters.join(",\n  ")
                ));
            }
        }
    }

    // 3. Extra Tables in Target (present in target, not in source)
    for tgt_tbl in &target.tables {
        if !is_included(&tgt_tbl.name) {
            continue;
        }
        if !source_tables.contains_key(tgt_tbl.name.as_str()) {
            summary.push(format!(
                "- Extra Table in Target: `{}` (Not in source)",
                tgt_tbl.name
            ));
            migration_sql.push_str(&format!(
                "-- Note: Table `{}` exists in target but not in source.\n",
                tgt_tbl.name
            ));
        }
    }

    if summary.is_empty() {
        summary.push("[OK] Schemas are identical! No migration necessary.".to_string());
        migration_sql.push_str("-- Schemas are completely synchronized.\n");
    }

    SchemaDiffReport {
        source_name: source.name.clone(),
        target_name: target.name.clone(),
        summary,
        migration_sql,
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn test_schema_diff_and_sync() {
        use crate::db::{ColumnInfo, DatabaseSchema, TableSchema};
        use crate::schema_diff::diff_schemas;

        let col_id = ColumnInfo {
            name: "id".to_string(),
            data_type: "INT".to_string(),
            is_nullable: false,
            is_primary_key: true,
            default_value: None,
            extra: "auto_increment".to_string(),
        };

        let col_name = ColumnInfo {
            name: "name".to_string(),
            data_type: "VARCHAR(255)".to_string(),
            is_nullable: false,
            is_primary_key: false,
            default_value: None,
            extra: String::new(),
        };

        let col_email = ColumnInfo {
            name: "email".to_string(),
            data_type: "VARCHAR(191)".to_string(),
            is_nullable: true,
            is_primary_key: false,
            default_value: None,
            extra: String::new(),
        };

        let source = DatabaseSchema {
            name: "prod_db".to_string(),
            tables: vec![
                TableSchema {
                    name: "users".to_string(),
                    table_type: "BASE TABLE".to_string(),
                    engine: "InnoDB".to_string(),
                    approx_rows: 10,
                    columns: vec![col_id.clone(), col_name.clone(), col_email.clone()],
                    foreign_keys: Vec::new(),
                    indexes: Vec::new(),
                },
                TableSchema {
                    name: "audit_logs".to_string(),
                    table_type: "BASE TABLE".to_string(),
                    engine: "InnoDB".to_string(),
                    approx_rows: 0,
                    columns: vec![col_id.clone()],
                    foreign_keys: Vec::new(),
                    indexes: Vec::new(),
                },
            ],
            ..Default::default()
        };

        let target = DatabaseSchema {
            name: "dev_db".to_string(),
            tables: vec![TableSchema {
                name: "users".to_string(),
                table_type: "BASE TABLE".to_string(),
                engine: "InnoDB".to_string(),
                approx_rows: 5,
                columns: vec![col_id.clone(), col_name.clone()], // missing email
                foreign_keys: Vec::new(),
                indexes: Vec::new(),
            }],
            ..Default::default()
        };

        let report = diff_schemas(&source, &target);
        assert!(
            report
                .migration_sql
                .contains("CREATE TABLE IF NOT EXISTS `audit_logs`")
        );
        assert!(report.migration_sql.contains("ALTER TABLE `users`"));
        assert!(
            report
                .migration_sql
                .contains("ADD COLUMN `email` VARCHAR(191) NULL")
        );
        assert_eq!(report.summary.len(), 2);
    }

    #[test]
    fn snapshot_schema_diff_create_table_ddl() {
        use crate::schema_diff::generate_create_table_ddl;
        use crate::test_fixtures::users_table;
        insta::assert_snapshot!(generate_create_table_ddl(&users_table()));
    }

    #[test]
    fn snapshot_schema_diff_format_column_defs() {
        use crate::schema_diff::format_column_def;
        use crate::test_fixtures::users_table;
        let defs: Vec<String> = users_table()
            .columns
            .iter()
            .map(format_column_def)
            .collect();
        insta::assert_snapshot!(defs.join("\n"));
    }

    #[test]
    fn test_diff_schemas_identical_is_empty() {
        use crate::db::DatabaseSchema;
        use crate::schema_diff::diff_schemas;
        use crate::test_fixtures::{orders_table, users_table};
        let schema = DatabaseSchema {
            name: "app".to_string(),
            tables: vec![users_table(), orders_table()],
            ..Default::default()
        };
        let report = diff_schemas(&schema, &schema);
        assert!(
            report
                .summary
                .iter()
                .all(|s| s.to_lowercase().contains("identical"))
        );
        assert!(!report.migration_sql.contains("CREATE TABLE"));
        assert!(!report.migration_sql.contains("ALTER TABLE"));
    }

    #[test]
    fn snapshot_schema_diff_missing_table() {
        use crate::db::DatabaseSchema;
        use crate::schema_diff::diff_schemas;
        use crate::test_fixtures::{orders_table, users_table};
        let source = DatabaseSchema {
            name: "src".to_string(),
            tables: vec![users_table(), orders_table()],
            ..Default::default()
        };
        let target = DatabaseSchema {
            name: "tgt".to_string(),
            tables: vec![users_table()],
            ..Default::default()
        };
        let report = diff_schemas(&source, &target);
        insta::assert_snapshot!(report.migration_sql);
    }

    #[test]
    fn snapshot_schema_diff_column_added_and_changed() {
        use crate::db::{ColumnInfo, DatabaseSchema, IndexInfo};
        use crate::schema_diff::diff_schemas;
        use crate::test_fixtures::users_table;
        let mut src_users = users_table();
        src_users.columns.push(ColumnInfo {
            name: "bio".to_string(),
            data_type: "text".to_string(),
            is_nullable: true,
            is_primary_key: false,
            default_value: None,
            extra: String::new(),
        });
        src_users.columns[2].data_type = "varchar(200)".to_string();
        src_users.indexes.push(IndexInfo {
            index_name: "idx_users_name".to_string(),
            column_name: "name".to_string(),
            non_unique: true,
            index_type: "BTREE".to_string(),
        });
        let source = DatabaseSchema {
            name: "src".to_string(),
            tables: vec![src_users],
            ..Default::default()
        };
        let target = DatabaseSchema {
            name: "tgt".to_string(),
            tables: vec![users_table()],
            ..Default::default()
        };
        let report = diff_schemas(&source, &target);
        let content = report
            .generate_migration_file_content()
            .lines()
            .map(|l| {
                if l.starts_with("-- Generated at: ") {
                    "-- Generated at: <TIMESTAMP>"
                } else {
                    l
                }
            })
            .collect::<Vec<_>>()
            .join("\n");
        insta::assert_snapshot!(content);
    }
}
